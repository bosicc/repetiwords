CREATE TABLE IF NOT EXISTS vocpt.word_lists (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 80),
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX IF NOT EXISTS word_lists_user_id_idx ON vocpt.word_lists(user_id);
CREATE TABLE IF NOT EXISTS vocpt.word_list_words (
  list_id INTEGER NOT NULL REFERENCES vocpt.word_lists(id) ON DELETE CASCADE,
  word_id INTEGER NOT NULL REFERENCES vocpt.words(id) ON DELETE CASCADE,
  PRIMARY KEY (list_id, word_id)
);
ALTER TABLE vocpt.word_lists ENABLE ROW LEVEL SECURITY;
ALTER TABLE vocpt.word_list_words ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON vocpt.word_lists, vocpt.word_list_words FROM PUBLIC;
