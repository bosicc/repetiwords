-- Keep application tables outside Supabase's public Data API schema.
CREATE SCHEMA IF NOT EXISTS vocpt;
REVOKE ALL ON SCHEMA vocpt FROM PUBLIC;

CREATE TABLE IF NOT EXISTS vocpt.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (length(trim(name)) > 0),
  email TEXT CHECK (email IS NULL OR length(trim(email)) > 0),
  created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_idx ON vocpt.users (lower(email));
CREATE TABLE IF NOT EXISTS vocpt.words (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  portuguese TEXT NOT NULL UNIQUE,
  english TEXT NOT NULL,
  level TEXT CHECK (level IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
  ukrainian TEXT,
  mastery_level INTEGER NOT NULL DEFAULT 0 CHECK (mastery_level BETWEEN 0 AND 5)
);
CREATE TABLE IF NOT EXISTS vocpt.sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE TABLE IF NOT EXISTS vocpt.groups (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE CHECK (length(trim(name)) > 0)
);
CREATE TABLE IF NOT EXISTS vocpt.word_groups (
  word_id INTEGER NOT NULL REFERENCES vocpt.words(id) ON DELETE CASCADE,
  group_id INTEGER NOT NULL REFERENCES vocpt.groups(id) ON DELETE CASCADE,
  PRIMARY KEY (word_id, group_id)
);
CREATE INDEX IF NOT EXISTS word_groups_group_id_idx ON vocpt.word_groups(group_id);
CREATE TABLE IF NOT EXISTS vocpt.answers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id INTEGER NOT NULL REFERENCES vocpt.sessions(id),
  word_id INTEGER NOT NULL REFERENCES vocpt.words(id),
  known INTEGER NOT NULL CHECK (known IN (0, 1)),
  revealed INTEGER NOT NULL DEFAULT 0 CHECK (revealed IN (0, 1)),
  created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
  UNIQUE(session_id, word_id)
);
CREATE INDEX IF NOT EXISTS answers_word_id_idx ON vocpt.answers(word_id);
CREATE TABLE IF NOT EXISTS vocpt.archived_words (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  original_word_id INTEGER NOT NULL,
  record_json TEXT NOT NULL,
  archived_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE TABLE IF NOT EXISTS vocpt.archived_answers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  original_answer_id INTEGER NOT NULL,
  archive_word_id INTEGER NOT NULL REFERENCES vocpt.archived_words(id),
  session_id INTEGER NOT NULL REFERENCES vocpt.sessions(id),
  known INTEGER NOT NULL CHECK (known IN (0, 1)),
  revealed INTEGER NOT NULL CHECK (revealed IN (0, 1)),
  created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS vocpt.session_words (
  session_id INTEGER NOT NULL REFERENCES vocpt.sessions(id),
  word_id INTEGER NOT NULL REFERENCES vocpt.words(id),
  position INTEGER NOT NULL CHECK (position >= 0),
  completed INTEGER NOT NULL DEFAULT 0 CHECK (completed IN (0, 1)),
  PRIMARY KEY (session_id, word_id),
  UNIQUE(session_id, position)
);

ALTER TABLE vocpt.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE vocpt.words ENABLE ROW LEVEL SECURITY;
ALTER TABLE vocpt.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE vocpt.groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE vocpt.word_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE vocpt.answers ENABLE ROW LEVEL SECURITY;
ALTER TABLE vocpt.archived_words ENABLE ROW LEVEL SECURITY;
ALTER TABLE vocpt.archived_answers ENABLE ROW LEVEL SECURITY;
ALTER TABLE vocpt.session_words ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA vocpt FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA vocpt FROM PUBLIC;
